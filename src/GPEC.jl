using GeneralizedPerturbedEquilibrium

Base.@kwdef mutable struct GPECSettings
    toroidal_mode_number::Int                           # toroidal mode number (nn_low = nn_high)
    wall::Union{Bool,Dict{String,<:Any}} = false   # false = nowall; true = conformal (needs `a`); Dict = advanced/manual
    a::Union{Real,Nothing} = nothing               # wall standoff, only used when wall=true
    kinetic_factor::Real = 0.0                     # 0 = ideal MHD (only mode currently wired up)
    # Inner-layer / Glasser stabilization inputs (Tearing workflow only -- ignored by the
    # ideal kink workflow). Not part of gpec.toml; passed straight to GPEC's
    # InnerLayer.SLAYER.build_slayer_inputs by TearingStability/Tearing.jl.
    chi_perp::Real = 1.0                           # perpendicular electron heat diffusivity [m^2/s] (GPEC's chi_perp_e)
    zeff::Real = 1.5                               # effective charge
    mu_i::Real = 2.0                               # ion mass in proton-mass units (2.0 = D)
    dc_type::Symbol = :fitzpatrick                 # critical-Delta formula: :none, :lar, :fitzpatrick, :toroidal (see SLAYERParameters)
end

function _resolve_wall(wall, a)
    wall === false && return Dict("shape" => "nowall")
    if wall === true
        a === nothing && error(
            "GPECSettings: wall=true requires the wall standoff `a` (plasma-boundary-to-wall " *
            "distance) to also be set, e.g. GPECSettings(..., wall=true, a=0.3)."
        )
        return Dict("shape" => "conformal", "a" => a)
    end
    wall isa Dict && return wall  # advanced/manual control, used as-is
    error("GPECSettings: `wall` must be `false` (no wall), `true` (conformal wall, requires `a`), " *
          "or a Dict for advanced shapes (got $(typeof(wall))).")
end

function run_GPEC(gpec_settings::GPECSettings, equilibrium_filename::String, test_dir::String)
    mkpath(test_dir)
    gpec_settings.kinetic_factor == 0 || error(
        "GPECSettings: kinetic_factor = $(gpec_settings.kinetic_factor) is not supported yet -- GPEC v2 " *
        "kinetic runs need a [KineticForces] section and an [Equilibrium] kinetic_file, which " *
        "make_gpec_toml does not write. Use kinetic_factor = 0 (ideal MHD).")
    wall = _resolve_wall(gpec_settings.wall, gpec_settings.a)
    toml_str = make_gpec_toml(equilibrium_filename, gpec_settings.toroidal_mode_number, wall)
    write(joinpath(test_dir, "gpec.toml"), toml_str)

    GPEC_output = GeneralizedPerturbedEquilibrium.main([test_dir]);
    return GPEC_output
end

function read_output(output::NamedTuple)
    ffs = output.ffs
    vd = ffs.free_boundary
    vd === nothing && error("read_output: no free_boundary result -- was vac_flag=true in gpec.toml?")

    dp = ffs.delta_prime
    delta_prime_matrix = (dp === nothing || isempty(dp.matrix)) ? nothing : dp.matrix
    # (m, n, q) for each singular surface, in the same order GPEC lists ffs.surfaces --
    # needed to look up which row/column of delta_prime_matrix belongs to a given mode,
    # since the matrix is indexed by surface, not by (m, n). See delta_prime_for_mode.
    singular_surfaces = [(m=copy(s.m), n=copy(s.n), q=s.q) for s in ffs.surfaces]

    return(
        dW_total = real(vd.et[1]),
        dW_plasma = real(vd.ep[1]),
        dW_vacuum = real(vd.ev[1]),
        et_full = vd.et,
        q0 = ffs.equil.params.q0,
        qmax = something(ffs.equil.params.qmax, ffs.qlim),
        msing = length(ffs.surfaces),
        delta_prime_matrix = delta_prime_matrix,  # classical linear tearing Δ' (PEST3 convention, ideal-MHD, kinetic_factor=0)
        singular_surfaces = singular_surfaces)
end

function make_gpec_toml(equilibrium_filename, toroidal_mode_number, wall) # eventually get rid of file writing in favor of direct calls to GPEC functions
    wall_block = _wall_toml(wall)
    n_tor_int  = Int(toroidal_mode_number)

    return """# Generated by TokToxStability for GPEC v2 (ideal MHD, free boundary, Riccati Delta').
# Settings audited against shaped_beta_scan/inputs/julia/gpec.toml and
# CTM-processing/CONVENTIONS.md (DIII-D 147131 reference settings).

[Run]
verbose = false

[Equilibrium]
eq_filename = "$equilibrium_filename"
eq_type     = "efit"          # gEQDSK reader
jac_type    = "hamada"        # Hamada (straight-field-line) coordinates
grid_type   = "auto"          # two-pass measured-curvature radial grid (with mpsi = 0)
mpsi        = 0               # 0 = let the auto grid size itself from psi_accuracy. Do NOT set a fixed
psi_accuracy = 1e-4           #   mpsi with "auto": its 3-region log layout converges slowly (D3D 147131
                              #   n=1: dW = 0.23 / 0.55 / 0.59 at mpsi = 257 / 513 / 1025 vs 0.588 converged)
psilow      = 1e-4            # inner psi bound (avoid the axis singularity)
psihigh     = 0.995           # outer psi bound (CONVENTIONS-recommended for D3D 147131)
mtheta      = 514             # poloidal grid points
newq0       = 0               # 0 = trust the input q0
flux_surface_rtol = 1e-10     # flux-surface tracing tolerance (v1 etol)

$wall_block
[ForceFreeStates]
integrator = "Riccati"        # chunked-propagator BVP; the only integrator that yields the Delta' matrix
vac_flag   = true             # free-boundary energies (et/ep/ev)

# --- Edge / rational-surface truncation -------------------------------------
truncate_at_rational_offset = true  # v1 set_psilim_via_dmlim
rational_offset_fraction    = 0.2   # v1 dmlim
qhigh              = 1e3      # effectively no q-cap; the rational offset governs psilim
qlow               = 1.02     # skip the q ~ 1 region (internal kink)
dW_edge_scan_start = 0.99     # edge-dW diagnostic band lower bound (v1 psiedge)

# --- Toroidal mode number ---------------------------------------------------
nn          = $n_tor_int
delta_mlow  = 8               # extend Fourier basis 8 harmonics below resonant m
delta_mhigh = 8               # ... and 8 above

# --- Numerics ---------------------------------------------------------------
mtheta_vacuum   = 960         # points in the plasma-vacuum spline (v1 mthvac)
singfac_min     = 1e-4        # fractional distance from rational where ideal jump enforced
frobenius_order = 6           # Frobenius expansion order at rationals (v1 sing_order)

[Riccati]
eulerlagrange_tolerance = 1e-10   # ODE integrator relative tol
renorm_threshold        = 1e4     # basis growth before renormalisation (v1 ucrit)
save_interval           = 3       # keep every 3rd ODE step (always saves near rationals)
"""
end

# v1-style wall keys (as accepted by GPECSettings' `wall` Dict) -> GPEC v2 [Wall] field names.
const _WALL_KEY_V2 = Dict("aw" => "half_thickness", "bw" => "elongation", "cw" => "center_offset",
                          "dw" => "triangularity", "tw" => "corner_sharpness")

"""
    _wall_toml(wall)

Emit the [Wall] section (empty for no wall -- GPEC v2 treats a missing [Wall] as no wall).
Accepts the v1 key names (`a`, `aw`, `bw`, `cw`, `dw`, `tw`) and translates them to v2's
(`standoff_fraction`/`minor_radius`, `half_thickness`, `elongation`, `center_offset`,
`triangularity`, `corner_sharpness`); v2 names pass through unchanged.
"""
function _wall_toml(wall)
    shape = wall["shape"]
    shape == "nowall" && return ""

    lines = ["[Wall]", "shape = \"$shape\""]
    for (k, v) in wall
        k == "shape" && continue
        key = k == "a" ? (shape in ("elliptical", "mod_dee") ? "minor_radius" : "standoff_fraction") :
              get(_WALL_KEY_V2, k, k)
        val = v isa AbstractString ? "\"$v\"" : v isa Bool ? string(v) : v
        push!(lines, "$key = $val")
    end
    return join(lines, "\n") * "\n"
end
